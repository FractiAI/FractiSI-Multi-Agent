/**
 * Layer E — Git and version management for FractiSI Multi-Agent.
 * Improves multi-agent workflow above Git; does not replace Git.
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

function runGit(cwd, args, opts = {}) {
  const result = spawnSync('git', args, {
    cwd,
    encoding: 'utf8',
    env: {
      ...process.env,
      GIT_TERMINAL_PROMPT: '0',
      GIT_AUTHOR_NAME: process.env.GIT_AUTHOR_NAME || 'FractiSI',
      GIT_AUTHOR_EMAIL: process.env.GIT_AUTHOR_EMAIL || 'fractisi@local',
      GIT_COMMITTER_NAME: process.env.GIT_COMMITTER_NAME || 'FractiSI',
      GIT_COMMITTER_EMAIL: process.env.GIT_COMMITTER_EMAIL || 'fractisi@local',
    },
  });
  if (result.error) {
    return { ok: false, error: result.error.message, stdout: '', stderr: String(result.stderr || '') };
  }
  if (result.status !== 0 && !opts.allowFail) {
    return {
      ok: false,
      error: `git ${args.join(' ')} failed`,
      stdout: result.stdout || '',
      stderr: result.stderr || '',
      status: result.status,
    };
  }
  return { ok: true, stdout: (result.stdout || '').trim(), stderr: (result.stderr || '').trim(), status: result.status };
}

function ensureGitRepo(root) {
  if (fs.existsSync(path.join(root, '.git'))) return { ok: true, created: false };
  fs.mkdirSync(root, { recursive: true });
  const init = runGit(root, ['init']);
  if (!init.ok) return init;
  runGit(root, ['config', 'user.name', 'FractiSI'], { allowFail: true });
  runGit(root, ['config', 'user.email', 'fractisi@local'], { allowFail: true });
  const readme = path.join(root, 'README.md');
  if (!fs.existsSync(readme)) {
    fs.writeFileSync(readme, '# FractiSI try sandbox\n\nGenerated by `node scripts/tiny.mjs try`.\n');
    runGit(root, ['add', 'README.md']);
    runGit(root, ['commit', '-m', 'chore: fractisi sandbox init'], { allowFail: true });
  }
  return { ok: true, created: true };
}

export function createGitIntegration(store, opts = {}) {
  function resolveRoot(explicit) {
    return explicit || store.state.project?.root || opts.cwd || process.cwd();
  }

  function inspect(cwd) {
    const root = resolveRoot(cwd);
    if (!fs.existsSync(path.join(root, '.git'))) {
      return { ok: false, root, error: 'not_a_git_repository' };
    }
    const branch = runGit(root, ['rev-parse', '--abbrev-ref', 'HEAD']);
    const head = runGit(root, ['rev-parse', 'HEAD']);
    const status = runGit(root, ['status', '--porcelain']);
    const remotes = runGit(root, ['remote', '-v'], { allowFail: true });
    const worktrees = runGit(root, ['worktree', 'list', '--porcelain'], { allowFail: true });
    return {
      ok: branch.ok && head.ok,
      root,
      branch: branch.ok ? branch.stdout : null,
      head: head.ok ? head.stdout : null,
      dirty: status.ok ? status.stdout.length > 0 : null,
      statusPorcelain: status.ok ? status.stdout : null,
      remotes: remotes.ok ? remotes.stdout : null,
      worktrees: worktrees.ok ? worktrees.stdout : null,
    };
  }

  function changedPaths(cwd) {
    const root = resolveRoot(cwd);
    const result = runGit(root, ['status', '--porcelain']);
    if (!result.ok) return { ok: false, paths: [], error: result.error };
    const paths = result.stdout
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean)
      .map((line) => line.replace(/^[A-Z?]{1,2}\s+/, '').replace(/^.* -> /, ''));
    return { ok: true, paths };
  }

  function allocateScopedWorkspace(agentId, input = {}) {
    if (!store.state.agents.has(agentId)) throw new Error(`unknown_agent:${agentId}`);
    const root = resolveRoot(input.cwd);
    const useWorktree = Boolean(input.useWorktree || opts.useWorktrees);
    const scope = {
      agentId,
      kind: useWorktree ? 'git_worktree' : 'scoped_virtual',
      root,
      label: input.label || `fractisi-${agentId}`,
      paths: [...(input.paths || [])],
      createdAt: new Date().toISOString(),
    };
    if (scope.kind === 'git_worktree') {
      ensureGitRepo(root);
      // Need at least one commit for worktree --detach from HEAD
      const head = runGit(root, ['rev-parse', 'HEAD'], { allowFail: true });
      if (!head.ok) {
        const readme = path.join(root, 'README.md');
        if (!fs.existsSync(readme)) fs.writeFileSync(readme, '# FractiSI\n');
        runGit(root, ['add', '-A']);
        runGit(root, ['commit', '-m', 'chore: seed for worktrees'], { allowFail: true });
      }
      const dest = input.path || path.join(root, '.fractisi', 'worktrees', agentId);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      if (!fs.existsSync(dest)) {
        const branch = `fractisi/${agentId}`;
        // Prefer branch worktree so agent can commit
        const created = runGit(root, ['worktree', 'add', '-b', branch, dest]);
        if (!created.ok) {
          // branch may exist — try without -b
          const retry = runGit(root, ['worktree', 'add', dest, branch], { allowFail: true });
          if (!retry.ok) {
            const detach = runGit(root, ['worktree', 'add', '--detach', dest]);
            if (!detach.ok) return { ok: false, error: detach.error || detach.stderr, scope };
          }
        }
        scope.branch = branch;
      }
      scope.path = dest;
    } else {
      scope.path = path.join(root, '.fractisi', 'workspaces', agentId);
      fs.mkdirSync(scope.path, { recursive: true });
    }
    const agent = store.state.agents.get(agentId);
    agent.workspace = scope;
    agent.updatedAt = new Date().toISOString();
    store.emit('git.workspace_allocated', { agentId, kind: scope.kind, path: scope.path });
    return { ok: true, scope };
  }

  function writeFiles(targetDir, files = {}) {
    const written = [];
    for (const [rel, content] of Object.entries(files)) {
      const abs = path.join(targetDir, rel);
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, typeof content === 'string' ? content : JSON.stringify(content, null, 2));
      written.push(rel);
    }
    return written;
  }

  /** Write contribution files into an agent workspace (worktree or virtual). */
  function applyContribution(agentId, contribution) {
    const agent = store.state.agents.get(agentId);
    if (!agent?.workspace?.path) throw new Error(`agent_workspace_missing:${agentId}`);
    const files = contribution.files || {};
    if (!Object.keys(files).length && contribution.paths?.length) {
      for (const p of contribution.paths) {
        files[p] = contribution.diff || contribution.summary || `// ${contribution.id}\n`;
      }
    }
    const written = writeFiles(agent.workspace.path, files);
    store.emit('git.contribution_applied', { agentId, contributionId: contribution.id, written });
    return { ok: true, workspace: agent.workspace.path, written };
  }

  /** Commit inside an agent worktree. */
  function commitWorkspace(agentId, message) {
    const agent = store.state.agents.get(agentId);
    if (!agent?.workspace?.path) throw new Error(`agent_workspace_missing:${agentId}`);
    const cwd = agent.workspace.path;
    if (agent.workspace.kind !== 'git_worktree') {
      // virtual workspace: copy into project root then commit there
      return { ok: false, error: 'virtual_workspace_use_integrateComposition' };
    }
    runGit(cwd, ['add', '-A']);
    const commit = runGit(cwd, ['commit', '-m', message || `fractisi: ${agentId}`], { allowFail: true });
    if (!commit.ok && !(commit.stderr || '').includes('nothing to commit')) {
      return { ok: false, error: commit.error || commit.stderr };
    }
    const sha = runGit(cwd, ['rev-parse', 'HEAD']);
    const entry = recordSafeCommit({
      compositionId: null,
      message: message || `fractisi: ${agentId}`,
      sha: sha.ok ? sha.stdout : null,
      agentId,
      workspace: cwd,
    });
    return { ok: true, sha: entry.sha, entry };
  }

  /**
   * Integrate composition file set into the project root and commit.
   * Copies contribution.files (or path placeholders) onto resolveRoot().
   */
  function integrateComposition(compositionId, optsIn = {}) {
    const composition = store.state.compositions.get(compositionId);
    if (!composition) throw new Error(`unknown_composition:${compositionId}`);
    if (!['validated', 'integrated', 'accepted'].includes(composition.state)) {
      throw new Error(`composition_not_ready:${composition.state}`);
    }
    const root = resolveRoot(optsIn.cwd);
    ensureGitRepo(root);
    const written = [];
    for (const cid of composition.contributionIds) {
      const c = store.state.contributions.get(cid);
      if (!c) continue;
      const files = { ...(c.files || {}) };
      if (!Object.keys(files).length) {
        for (const p of c.paths || []) files[p] = `${c.summary || c.id}\n`;
      }
      written.push(...writeFiles(root, files));
    }
    runGit(root, ['add', '-A']);
    const msg = optsIn.message || `fractisi: integrate ${compositionId}`;
    const commit = runGit(root, ['commit', '-m', msg], { allowFail: true });
    const nothing = (commit.stderr || commit.stdout || '').toLowerCase().includes('nothing to commit');
    if (!commit.ok && !nothing) {
      return { ok: false, error: commit.error || commit.stderr, written };
    }
    const sha = runGit(root, ['rev-parse', 'HEAD']);
    const entry = recordSafeCommit({
      compositionId,
      message: msg,
      sha: sha.ok ? sha.stdout : null,
      written,
    });
    composition.state = 'integrated';
    composition.gitSha = entry.sha;
    composition.updatedAt = new Date().toISOString();
    for (const cid of composition.contributionIds) {
      const c = store.state.contributions.get(cid);
      if (c) c.state = 'integrated';
    }
    store.emit('git.composition_integrated', { compositionId, sha: entry.sha });
    return { ok: true, sha: entry.sha, written, entry };
  }

  function removeWorkspace(agentId) {
    const agent = store.state.agents.get(agentId);
    if (!agent?.workspace?.path) return { ok: true, removed: false };
    const root = resolveRoot();
    if (agent.workspace.kind === 'git_worktree') {
      runGit(root, ['worktree', 'remove', '--force', agent.workspace.path], { allowFail: true });
    }
    store.emit('git.workspace_removed', { agentId });
    return { ok: true, removed: true };
  }

  function recordSafeCommit(meta = {}) {
    const entry = {
      id: `commit_meta_${Date.now()}`,
      compositionId: meta.compositionId || null,
      agentId: meta.agentId || null,
      message: meta.message || '',
      sha: meta.sha || null,
      written: meta.written || [],
      workspace: meta.workspace || null,
      at: new Date().toISOString(),
    };
    store.state.commits.push(entry);
    if (store.state.commits.length > 200) store.state.commits.shift();
    store.emit('git.safe_commit_recorded', entry);
    return entry;
  }

  return {
    inspect,
    changedPaths,
    allocateScopedWorkspace,
    applyContribution,
    commitWorkspace,
    integrateComposition,
    removeWorkspace,
    recordSafeCommit,
    ensureGitRepo,
    runGit,
    writeFiles,
  };
}
